import { readFileSync } from 'fs';
import { join } from 'path';
import { logoPaths } from '@/components/logos/paths';

// The twelve hero marks (D78), then the /skills graph's thirteen (P5-02, D98), in the generator's order
const KEYS = [
  'claude', 'livekit', 'python', 'typescript', 'bash', 'sqlite',
  'postgresql', 'docker', 'linux', 'nextjs', 'n8n', 'github',
  'react', 'nodedotjs', 'vercel', 'tailscale', 'supabase', 'openjdk', 'cplusplus',
  'linear', 'zapier', 'tailwindcss', 'javascript', 'expo', 'modelcontextprotocol',
];

describe('logoPaths', () => {
  it('has exactly the 25 keys', () => {
    expect(KEYS).toHaveLength(25);
    expect(Object.keys(logoPaths)).toEqual(KEYS);
  });

  it.each(KEYS)('%s has a title and a path that starts with a moveto', (key) => {
    const { title, path } = logoPaths[key as keyof typeof logoPaths];
    expect(title.trim()).not.toBe('');
    // siClaude.path starts with a relative 'm' (valid SVG), so either case
    expect(path).toMatch(/^[Mm]/);
    expect(path.length).toBeGreaterThan(20);
  });

  it('labels the overridden marks Claude Code and Bash', () => {
    expect(logoPaths.claude.title).toBe('Claude Code');
    expect(logoPaths.bash.title).toBe('Bash');
  });

  it('labels the skills-graph overrides Java, C++ and MCP', () => {
    expect(logoPaths.openjdk.title).toBe('Java');
    expect(logoPaths.cplusplus.title).toBe('C++');
    expect(logoPaths.modelcontextprotocol.title).toBe('MCP');
  });

  it('is still generated (header line)', () => {
    const src = readFileSync(join(process.cwd(), 'src/components/logos/paths.ts'), 'utf8');
    expect(src.split('\n')[0]).toBe('// GENERATED by scripts/logos.mjs (npm run logos); do not edit by hand.');
  });
});
