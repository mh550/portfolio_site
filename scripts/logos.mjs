// Generates src/components/logos/paths.ts from simple-icons (a devDependency, D78): the site never imports
// simple-icons at runtime. Run by hand (`npm run logos`) after editing ICONS; commit the output. Deterministic
// (fixed order, no timestamp), so a second run leaves git status clean.
import { readFile, writeFile } from 'node:fs/promises';
import * as icons from 'simple-icons';

// key on the site, simple-icons export, and a title when the site's label differs from the brand's
